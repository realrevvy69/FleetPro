import jsPDF from "jspdf";
import { formatDate, formatNumber } from "./format";

export const downloadCSV = (apiBase, path, filename) => {
  const url = `${apiBase}${path}`;
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
};

export const generateProtocolPDF = (handover, ret, vehicle) => {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const margin = 40;
  let y = margin;

  // Header
  doc.setFillColor(10, 10, 10);
  doc.rect(0, 0, W, 70, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.text("FleetPro", margin, 35);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(180, 180, 180);
  doc.text("Vehicle Handover & Return Protocol", margin, 55);
  y = 100;

  // Vehicle info
  doc.setTextColor(0, 0, 0);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("Vehicle", margin, y);
  y += 6;
  doc.setLineWidth(0.5);
  doc.line(margin, y, W - margin, y);
  y += 18;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  const vehicleLabel = vehicle ? `${vehicle.brand} ${vehicle.model}` : "Unknown";
  const plate = vehicle ? vehicle.license_plate : "—";
  doc.text(`${vehicleLabel}    •    Plate: ${plate}`, margin, y);
  y += 24;

  const renderProtocol = (title, p) => {
    if (!p) return;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.text(title, margin, y);
    y += 6;
    doc.line(margin, y, W - margin, y);
    y += 16;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    const rows = [
      ["Driver", p.driver_name],
      ["Date", formatDate(p.created_at)],
      ["Mileage", `${formatNumber(p.mileage)} km`],
      ["Fuel Level", `${p.fuel_level}%`],
    ];
    rows.forEach(([k, v]) => {
      doc.setTextColor(110, 110, 110);
      doc.text(k, margin, y);
      doc.setTextColor(0, 0, 0);
      doc.text(String(v), margin + 90, y);
      y += 14;
    });

    y += 4;
    doc.setTextColor(110, 110, 110);
    doc.text("Extras", margin, y);
    doc.setTextColor(0, 0, 0);
    const extrasText = (p.extras || [])
      .map((e) => `${e.present ? "✓" : "✗"} ${e.name}`)
      .join("    ");
    const split = doc.splitTextToSize(extrasText || "—", W - margin - 90);
    doc.text(split, margin + 90, y);
    y += split.length * 12 + 8;

    if (p.signature_base64) {
      doc.setTextColor(110, 110, 110);
      doc.text("Signature", margin, y);
      y += 6;
      try {
        doc.addImage(p.signature_base64, "PNG", margin, y, 200, 70);
      } catch (e) {}
      y += 80;
    }
    y += 14;
    if (y > 720) { doc.addPage(); y = margin; }
  };

  renderProtocol("Handover Protocol", handover);
  if (ret) renderProtocol("Return Protocol", ret);

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(140, 140, 140);
  doc.text(
    `Generated by FleetPro on ${new Date().toLocaleString()}`,
    margin,
    doc.internal.pageSize.getHeight() - 20
  );

  const filename = `protocol_${(vehicle?.license_plate || "vehicle").replace(/\s+/g, "_")}_${handover.id.slice(0, 8)}.pdf`;
  doc.save(filename);
};
